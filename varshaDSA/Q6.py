# Program using set

# a. Create empty set
my_set = set()
print("Empty set:", my_set)

# b. Assign value to set
my_set = {1, 2, 3}
print("Assigned set:", my_set)

# c. Adding element
my_set.add(4)
print("After adding element:", my_set)

# d. Removing element
my_set.remove(2)
print("After removing element:", my_set)
